/**
 * The text of the Privacy Policy and the Terms of Service.
 *
 * Every statement about what Reclip stores, keeps or does is written from how the software
 * actually behaves, and the retention figures are imported from the code that enforces them.
 * It is a draft for a lawyer to review, not legal advice.
 */

export interface LegalSection {
  id: string;
  heading: string;
  paragraphs?: string[];
  bullets?: string[];
  table?: { head: string[]; rows: string[][] };
  after?: string[];
}

/** The one list of sub-processors, used by the Privacy Policy and the Data Processing Addendum. */
export function subprocessorTable(c: LegalConfig): { head: string[]; rows: string[][] } {
  return {
    head: ['Provider', 'What it does', 'What it can see'],
    rows: [
      ['Railway', 'Runs the application and the database', 'Everything stored in the database, in the region below'],
      [c.storageProvider, 'Stores uploaded documents and encrypted backups', 'Your uploaded documents; backups are encrypted and unreadable to the provider'],
      [c.emailProvider, 'Delivers our emails', 'Your email address and the content of the emails we send you'],
      ['Anthropic or OpenAI (only if enabled)', 'Reads photographed receipts', 'The image you uploaded, while it is being read'],
      ['Sentry (only if enabled)', 'Tells us when something breaks', 'Error details with personal data removed: no names, emails, documents, cookies or query values'],
    ],
  };
}

